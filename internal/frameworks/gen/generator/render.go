package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"
)

const generatedSourceTemplate = `// Code generated by "go generate ./internal/frameworks/..."; DO NOT EDIT.

package frameworks

import (
{{- range .Imports }}
	"govard/internal/frameworks/{{ . }}"
{{- end }}
	"govard/internal/frameworks/types"
)

func init() {
	RegisterSpecs([]types.FrameworkSpec{
{{- range .Order }}
		{{ . }}.Spec(),
{{- end }}
	})
}
`

type generatedSourceData struct {
	Imports []string // alphabetized - import order doesn't affect registration
	Order   []string // priority-then-name order - this is what controls Register() sequencing
}

// RenderSource builds the formatted contents of all_generated.go.
// alphabetical drives the import block; order drives the sequence of specs
// projected into engine's detection registry (the two differ only when
// PriorityOverrides reorders a package ahead of its alphabetical
// position).
func RenderSource(alphabetical []string, order []string) ([]byte, error) {
	tmpl, err := template.New("all_generated").Parse(generatedSourceTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	data := generatedSourceData{Imports: alphabetical, Order: order}
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, nil
}
