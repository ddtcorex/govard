#!/usr/bin/env node
// @ts-check
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  parseServiceReturnTypes,
  parseServiceMethodIds,
  classifyReturnType,
} from "./route-defaults-parser.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const bindingsDir = join(__dirname, "..", "bindings", "govard", "internal", "desktop");
const outDefaults = join(__dirname, "..", "preview", "route-defaults.generated.js");
const outIdMap = join(__dirname, "..", "preview", "id-map.generated.js");

const indexSource = readFileSync(join(bindingsDir, "index.js"), "utf8");
const importRe = /import \* as (\w+) from "\.\/(\w+)\.js";/g;
const services = [...indexSource.matchAll(importRe)].map((m) => ({
  service: m[1],
  file: m[2],
}));

/** @type {Record<string, any>} */
const routeDefaults = {};
/** @type {Record<string, {service: string, method: string}>} */
const idMap = {};

for (const { service, file } of services) {
  const source = readFileSync(join(bindingsDir, `${file}.js`), "utf8");
  for (const { name, type } of parseServiceReturnTypes(source)) {
    routeDefaults[`${service}.${name}`] = classifyReturnType(type);
  }
  for (const { name, id } of parseServiceMethodIds(source)) {
    idMap[id] = { service, method: name };
  }
}

const header = `// @ts-check\n// Generated by scripts/generate-preview-route-defaults.mjs. DO NOT EDIT.\n// Regenerate with: node desktop/frontend/scripts/generate-preview-route-defaults.mjs\n`;

writeFileSync(
  outDefaults,
  `${header}\nexport const ROUTE_DEFAULTS = ${JSON.stringify(routeDefaults, null, 2)};\n`,
);
writeFileSync(
  outIdMap,
  `${header}\nexport const ID_MAP = ${JSON.stringify(idMap, null, 2)};\n`,
);

console.log(
  `Wrote ${Object.keys(routeDefaults).length} route defaults, ${Object.keys(idMap).length} id-map entries.`,
);
